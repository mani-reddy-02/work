const normalize = (str: string) => str.toLowerCase().replace(/[^a-z0-9]/g, '');

const normalizedIconMap: Record<string, string> = {};
allIcons.forEach(icon => {
  const baseName = icon.replace('.webp', '');
  normalizedIconMap[normalize(baseName)] = `/optimized/${icon}`;
});

export const getDiseaseIconUrl = (
  diseaseName?: string | null,
  dbIconName?: string | null,
  categoryName?: string | null
): string => {
  // 1. Direct DB icon match
  if (dbIconName) {
    if (dbIconName.startsWith('/') || dbIconName.startsWith('http')) {
      return dbIconName;
    }
    const cleanDbIcon = dbIconName.replace(/^\/+/, '');
    if (allIcons.includes(cleanDbIcon) || allIcons.includes(`${cleanDbIcon}.webp`)) {
      const fileName = cleanDbIcon.endsWith('.webp') ? cleanDbIcon : `${cleanDbIcon}.webp`;
      return `/optimized/${fileName}`;
    }
    if (cleanDbIcon.endsWith('.jpg') || cleanDbIcon.endsWith('.png') || cleanDbIcon.endsWith('.webp')) {
      return `/icons/${cleanDbIcon}`;
    }
  }

  // 2. Lookup by diseaseName
  if (diseaseName) {
    const trimmed = diseaseName.trim().toLowerCase();
    
    // Exact mapping check
    if (specificMap[trimmed]) {
      return specificMap[trimmed];
    }

    // Normalized direct match
    const normName = normalize(diseaseName);
    if (normalizedIconMap[normName]) {
      return normalizedIconMap[normName];
    }

    // Singular form match (remove trailing 's')
    if (normName.endsWith('s') && normalizedIconMap[normName.slice(0, -1)]) {
      return normalizedIconMap[normName.slice(0, -1)];
    }

    // DepartmentIcons check for direct specialty match
    if (departmentIcons[diseaseName] && departmentIcons[diseaseName].length > 0) {
      return `/optimized/${departmentIcons[diseaseName][0]}`;
    }

    // Keyword / Symptom matching
    for (const rule of keywordRules) {
      if (rule.regex.test(diseaseName)) {
        return `/optimized/${rule.icon}`;
      }
    }
  }

  // 3. Fallback to categoryName context
  if (categoryName) {
    const trimmedCat = categoryName.trim().toLowerCase();
    if (specificMap[trimmedCat]) {
      return specificMap[trimmedCat];
    }
    if (departmentIcons[categoryName] && departmentIcons[categoryName].length > 0) {
      return `/optimized/${departmentIcons[categoryName][0]}`;
    }
    for (const rule of keywordRules) {
      if (rule.regex.test(categoryName)) {
        return `/optimized/${rule.icon}`;
      }
    }
  }

  // 4. Default medical icon fallback
  return '/optimized/Blood Test.webp';
};